-- =====================================================================
--  SQL Playground - practice database schema
--  "Mishti & More": a small chain of sweet shops with stores, staff,
--  products, customers, online + in-store orders, payments and reviews.
--
--  Designed for learning joins: several relationships are OPTIONAL on
--  purpose (nullable foreign keys) and some rows have no match on the
--  other side, so LEFT / RIGHT / FULL joins produce visible NULLs.
--
--  This file is executed (with the other files in db/seed, in name
--  order) to build the template database. "Reset DB" clones it again.
-- =====================================================================

CREATE TABLE departments (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    text NOT NULL UNIQUE,
  budget  numeric(12,2) CHECK (budget >= 0)              -- NULL = budget not decided yet
);
COMMENT ON TABLE departments IS 'Company departments. One department has no employees yet.';

CREATE TABLE stores (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL UNIQUE,
  city       text NOT NULL,
  opened_on  date NOT NULL
);
COMMENT ON TABLE stores IS 'Physical shops. The newest store has no orders yet.';

CREATE TABLE employees (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name     text NOT NULL,
  last_name      text NOT NULL,
  email          text NOT NULL UNIQUE,
  title          text NOT NULL,
  department_id  integer REFERENCES departments(id) ON DELETE SET NULL,  -- NULL = contractor, no department
  manager_id     integer REFERENCES employees(id) ON DELETE SET NULL,    -- self-reference; NULL = top of the org chart
  store_id       integer REFERENCES stores(id) ON DELETE SET NULL,       -- NULL = head-office / not store based
  salary         numeric(10,2) NOT NULL CHECK (salary > 0),               -- monthly, in INR
  hire_date      date NOT NULL
);
COMMENT ON TABLE employees IS 'Staff. manager_id points back at employees (use a SELF JOIN).';

CREATE TABLE salary_grades (
  grade       text PRIMARY KEY,
  min_salary  numeric(10,2) NOT NULL,
  max_salary  numeric(10,2) NOT NULL,
  CHECK (min_salary < max_salary)
);
COMMENT ON TABLE salary_grades IS 'Salary bands. No foreign key: join with BETWEEN (a non-equi join).';

CREATE TABLE categories (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL UNIQUE,
  parent_id  integer REFERENCES categories(id) ON DELETE SET NULL      -- tree of categories (recursive CTE)
);
COMMENT ON TABLE categories IS 'Product categories arranged as a tree via parent_id. Some categories are empty.';

CREATE TABLE products (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text NOT NULL UNIQUE,
  category_id  integer REFERENCES categories(id) ON DELETE SET NULL,   -- one product is uncategorised
  unit         text NOT NULL CHECK (unit IN ('piece', 'kg', 'box', 'pack', 'cup')),
  price        numeric(10,2) NOT NULL CHECK (price > 0),               -- current price, INR per unit
  cost         numeric(10,2) CHECK (cost >= 0),                        -- NULL = cost unknown
  is_active    boolean NOT NULL DEFAULT true,
  launched_on  date NOT NULL
);
COMMENT ON TABLE products IS 'Things we sell. A few products have never been ordered.';

CREATE TABLE suppliers (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name   text NOT NULL UNIQUE,
  city   text NOT NULL,
  phone  text
);
COMMENT ON TABLE suppliers IS 'Raw-material suppliers. One supplier supplies nothing yet.';

CREATE TABLE product_suppliers (
  product_id   integer NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  supplier_id  integer NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,
  unit_cost    numeric(10,2) NOT NULL CHECK (unit_cost >= 0),
  PRIMARY KEY (product_id, supplier_id)
);
COMMENT ON TABLE product_suppliers IS 'Junction table for the many-to-many link between products and suppliers.';

CREATE TABLE customers (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name   text NOT NULL,
  last_name    text NOT NULL,
  email        text UNIQUE,                                            -- NULL = never shared
  phone        text,
  city         text,
  signup_date  date NOT NULL,
  referred_by  integer REFERENCES customers(id) ON DELETE SET NULL     -- self-reference: who referred them
);
COMMENT ON TABLE customers IS 'Registered customers. Some have never placed an order.';

CREATE TABLE orders (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  integer REFERENCES customers(id) ON DELETE SET NULL,    -- NULL = anonymous walk-in
  store_id     integer REFERENCES stores(id),                          -- NULL = online order
  employee_id  integer REFERENCES employees(id) ON DELETE SET NULL,    -- staff member who handled it
  ordered_at   timestamp NOT NULL,
  status       text NOT NULL DEFAULT 'pending'
               CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
  discount     numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 100)  -- percent off the order
);
COMMENT ON TABLE orders IS 'Order headers. Order value = SUM(order_items.quantity * unit_price) minus discount %.';

CREATE TABLE order_items (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id  integer NOT NULL REFERENCES products(id),
  quantity    integer NOT NULL CHECK (quantity > 0),
  unit_price  numeric(10,2) NOT NULL CHECK (unit_price >= 0),          -- price at the time of the order
  UNIQUE (order_id, product_id)
);
COMMENT ON TABLE order_items IS 'Order lines. A couple of orders have no lines at all.';

CREATE TABLE payments (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id  integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  method    text NOT NULL CHECK (method IN ('upi', 'card', 'cash', 'wallet')),
  amount    numeric(10,2) NOT NULL CHECK (amount > 0),
  paid_at   timestamp NOT NULL
);
COMMENT ON TABLE payments IS 'Payments. Pending/cancelled orders have none; some orders were split into two payments.';

CREATE TABLE reviews (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id   integer NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  customer_id  integer REFERENCES customers(id) ON DELETE SET NULL,
  rating       smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment      text,                                                   -- NULL = rating only
  created_at   timestamp NOT NULL
);
COMMENT ON TABLE reviews IS 'Product reviews (1-5 stars).';

CREATE TABLE web_events (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  integer REFERENCES customers(id) ON DELETE SET NULL,    -- NULL = visitor not logged in
  product_id   integer REFERENCES products(id) ON DELETE SET NULL,
  event_type   text NOT NULL,
  device       text NOT NULL,
  occurred_at  timestamp NOT NULL
);
COMMENT ON TABLE web_events IS '200,000 website events with NO secondary indexes - for the indexes / EXPLAIN lessons.';
